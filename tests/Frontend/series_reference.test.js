import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

test('series framing changes with crop, contain and subject role; removal and disconnect release local previews', () => {
    const released = [];
    const source = readFileSync(new URL('../../assets/controllers/series_reference_controller.js', import.meta.url), 'utf8').replace("import { Controller } from '@hotwired/stimulus';", '').replace('export default class', 'class Reference');
    const Reference = runInNewContext(`${source}\nReference`, { Controller: class {}, Event: class {}, URL: { createObjectURL: () => 'blob:local', revokeObjectURL: url => released.push(url) } });
    const controller = new Reference();
    const model = {selectedOptions:[{dataset:{subject:'false'}}]};
    const ratio = {value:'9:16'};
    const fit = {value:'crop'};
    controller.previewTarget = {naturalWidth:800,naturalHeight:600,style:{},getAttribute() { return this.src; },removeAttribute() { this.src = ''; }};
    const fields = { '[data-series-settings-target="model"]':model, '[data-series-settings-target="ratio"]':ratio, '[name="ai_series[imageFit]"]':fit, '[data-series-reference-slot="start"] img':controller.previewTarget };
    const form = {querySelector: selector => fields[selector],addEventListener() {},removeEventListener() {}};
    controller.element = {closest: () => form};
    controller.originalValue = '/private/original.jpg';
    controller.fileTarget = {files:[{type:'image/png',size:100}],value:'selected'};
    controller.frameTarget = {style:{}};
    controller.removeTarget = {checked:false,dispatchEvent() {}};
    controller.clearTarget = {};
    controller.statusTarget = {};
    controller.connect();
    assert.equal(controller.previewTarget.src, '/private/original.jpg');
    assert.equal(controller.frameTarget.style.aspectRatio, '9 / 16');
    assert.equal(controller.previewTarget.style.objectFit, 'cover');
    fit.value = 'contain'; controller.render();
    assert.equal(controller.previewTarget.style.objectFit, 'contain');
    assert.match(controller.statusTarget.textContent, /bandes noires/);
    model.selectedOptions[0].dataset.subject = 'true'; controller.render();
    assert.equal(controller.frameTarget.style.aspectRatio, '800 / 600');
    assert.match(controller.statusTarget.textContent, /sans imposer/);
    controller.select();
    assert.equal(controller.previewTarget.src, 'blob:local');
    controller.remove();
    assert.equal(controller.removeTarget.checked, true);
    assert.equal(controller.fileTarget.value, '');
    assert.equal(controller.frameTarget.hidden, true);
    assert.deepEqual(released, ['blob:local']);
    controller.select(); controller.disconnect();
    assert.deepEqual(released, ['blob:local', 'blob:local']);
});
